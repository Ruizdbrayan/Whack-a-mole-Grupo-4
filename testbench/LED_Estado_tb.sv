`timescale 1ns / 1ps

module tb_status_led_driver;

    logic clk;
    logic estado_partida;
    logic led_estado;

    // =========================================================
    // DUT
    // =========================================================

    status_led_driver leds_estado (
        .clk(clk),
        .estado_partida(estado_partida),
        .led_estado(led_estado)
    );

    // =========================================================
    // RELOJ DE 100 MHz
    // Periodo = 10 ns
    // =========================================================

    always begin
        #5 clk = ~clk;
    end

    // =========================================================
    // TEST
    // =========================================================

    initial begin

        clk = 0;
        estado_partida = 0;

        // -----------------------------------------------------
        // Estado inicial
        // -----------------------------------------------------

        #100;

        // -----------------------------------------------------
        // Simular derrota
        // -----------------------------------------------------

        estado_partida = 1;

        // Mantener derrota activa
        #100;

        estado_partida = 0;

        // -----------------------------------------------------
        // Esperar los 2 segundos
        // -----------------------------------------------------

        #2_000_000_000;

        // -----------------------------------------------------
        // Finalizar simulación
        // -----------------------------------------------------

        $finish;

    end

endmodule